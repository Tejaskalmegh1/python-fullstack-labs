# data types in python 

name = "Tejas"                     # str
age = 25                           # int
height = 5.9                       # float
is_student = True                  # bool
skills = ["Python", "C", "C++"]    # list
colors = ("Red", "Green")          # tuple
numbers = {1, 2, 3, 4}             # set
student = {"name": "Tejas", "age": 25}  # dict

print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
print(type(skills))
print(type(colors))
print(type(numbers))
print(type(student))

